def require_reset_permission(names):
    context = op.get_context()
    if context.as_sql:
        return
    connection = op.get_bind()
    schema = context.opts.get("dxos_schema", "public")
    preparer = connection.dialect.identifier_preparer
    targets = ", ".join(
        preparer.quote_schema(schema) + "." + preparer.quote_identifier(name)
        for name in names
    )
    connection.execute(sa.text("SET LOCAL lock_timeout = '5s'"))
    connection.execute(sa.text("LOCK TABLE " + targets + " IN ACCESS EXCLUSIVE MODE"))
    if context.config.attributes.get("allow_core_data_reset") is True:
        return
    for name in names:
        target = preparer.quote_schema(schema) + "." + preparer.quote_identifier(name)
        if connection.scalar(sa.text("SELECT EXISTS (SELECT 1 FROM " + target + " LIMIT 1)")):
            raise RuntimeError(
                "Core contains metadata. Use the guarded realign-core command with an explicit backup."
            )


