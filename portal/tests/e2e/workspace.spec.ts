test('knowledge chat sends without a PR picker or purchase request lookup', async ({ page }) => {
  const purchaseReads: string[] = []
  page.on('request', request => {
    if (request.url().includes('/purchase-requests')) purchaseReads.push(request.url())
  })
  await page.goto('/?preview=1')
  await page.getByRole('button', { name: 'Tìm kiếm tài liệu', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Bỏ agent Tri thức', exact: true })).toBeVisible()
  await expect(page.getByText('Ngữ cảnh PR', { exact: true })).toHaveCount(0)
  await expect(page.getByRole('combobox')).toHaveCount(0)
  await page.getByRole('textbox', { name: 'Tin nhắn', exact: true }).fill('Tra cứu tài liệu dùng chung')
  await page.getByRole('button', { name: 'Gửi tin nhắn', exact: true }).click()
  await expect(page.locator('[data-message-role="user"]')).toContainText('Tra cứu tài liệu dùng chung')
  await expect(page.getByRole('img', { name: /Tiến độ giao hàng/ })).toBeVisible()
  expect(purchaseReads).toEqual([])
})
