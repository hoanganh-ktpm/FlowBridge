test('reading column stays centered and composer expands without viewport overflow', async ({ page }) => {
  for (const viewport of [{ width: 1440, height: 900 }, { width: 1024, height: 768 }, { width: 390, height: 844 }, { width: 320, height: 640 }]) {
    await page.setViewportSize(viewport)
    await page.goto('/?preview=1')
    const heading = page.getByRole('heading', { name: /Tôi là FlowBridge, tôi có thể giúp bạn/ })
    await expect(heading).toBeVisible()
    const composer = page.locator('.chat-composer')
    const main = await page.locator('.workspace-main').boundingBox()
    const bounds = await composer.boundingBox()
    expect(Math.abs((bounds!.x + bounds!.width / 2) - (main!.x + main!.width / 2))).toBeLessThan(2)
    expect(bounds!.height).toBeLessThan(60)
    expect(bounds!.width).toBeLessThanOrEqual(672)
    await expect(composer).toHaveAttribute('data-slot', 'input-group')
    const header = await page.locator('.workspace-header').boundingBox()
    expect(header!.height).toBeLessThanOrEqual(56)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: `ref/qa/redesign-${viewport.width}.png`, fullPage: true, animations: 'disabled' })
    await page.getByRole('textbox', { name: 'Tin nhắn', exact: true }).fill('Phân tích giao hàng\nSo sánh nhà cung cấp trong tháng này.')
    await expect(composer).toHaveClass(/is-expanded/)
    await expect(page.getByRole('button', { name: 'Gửi tin nhắn', exact: true })).toBeEnabled()
    const expanded = await composer.boundingBox()
    expect(expanded!.height).toBeGreaterThan(bounds!.height)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  }
})

