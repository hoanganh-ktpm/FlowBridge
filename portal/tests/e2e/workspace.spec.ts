test('history restores after reload, rename and clarification use the correct run', async ({ page }) => {
  await page.goto('/?preview=1')
  await page.getByRole('button', { name: 'So sánh nhà cung cấp', exact: true }).click()
  await expect(page.locator('.result-chart')).toHaveCount(4)
  await page.reload()
  await expect(page.locator('.result-chart')).toHaveCount(4)
  await page.getByRole('button', { name: 'Tùy chọn So sánh nhà cung cấp' }).click()
  await page.getByRole('menuitem', { name: 'Đổi tên', exact: true }).click()
  await page.getByRole('textbox', { name: 'Tên hội thoại' }).fill('So sánh giao hàng')
  await page.getByRole('button', { name: 'Lưu tên', exact: true }).click()
  await expect(page.getByRole('button', { name: 'So sánh giao hàng', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Tùy chọn So sánh giao hàng' }).click()
  await page.getByRole('menuitem', { name: 'Xóa', exact: true }).click()
  await expect(page.getByRole('button', { name: 'So sánh giao hàng', exact: true })).toHaveCount(0)
  await page.keyboard.press('Control+k')
  await page.getByRole('textbox', { name: 'Tìm hội thoại' }).fill('Lập yêu cầu')
  await page.getByRole('dialog').getByRole('button', { name: 'Lập yêu cầu mua hàng' }).click()
  await expect(page.locator('[data-message-role="assistant"]')).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Bổ sung thông tin' })).toHaveCount(0)
})

