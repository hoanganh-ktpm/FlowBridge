"""Four isolated module schemas can coexist with unrelated Supabase data.

These tests create one randomly named disposable database on the explicit test
server. They never read a .env target URL or alter a pre-existing database.
"""

import os
from io import StringIO
from uuid import uuid4

import pytest
from alembic import command
from alembic.util.exc import AutogenerateDiffsDetected
from scripts.database.config import database_url, schema_for, validate_distinct_targets
from scripts.database.engine import make_engine
from scripts.database.migration import alembic_config
from scripts.database.registry import DATABASES, metadata_for
from sqlalchemy import create_engine, inspect, select, text
from sqlalchemy.engine import make_url
from sqlalchemy.exc import IntegrityError

pytestmark = [pytest.mark.integration, pytest.mark.e2e]


@pytest.fixture(scope="module")
def shared_database():
    value = os.environ.get("DXOS_TEST_ADMIN_URL")
    if not value:
        pytest.skip("Set DXOS_TEST_ADMIN_URL for PostgreSQL integration tests")
    admin_url = make_url(value)
    assert admin_url.drivername == "postgresql+psycopg"
    suffix = uuid4().hex[:10]
    dbname = f"dxos_it_schemas_{suffix}"
    url = admin_url.set(database=dbname)
    admin = create_engine(admin_url, isolation_level="AUTOCOMMIT")
    patch = pytest.MonkeyPatch()
    raw = None
    engines = {}
    created = False
    try:
        with admin.connect() as conn:
            quoted = conn.dialect.identifier_preparer.quote_identifier(dbname)
            conn.exec_driver_sql(f"CREATE DATABASE {quoted}")
            created = True
        patch.setenv("DXOS_LAYOUT", "schemas")
        patch.setenv("DXOS_DATABASE_URL", url.render_as_string(hide_password=False))
        for name in DATABASES:
            # Alembic loads .env with override=False. Every target must already
            # be explicit so an unrelated local .env can never fill a missing
            # variable with a live Supabase URL during a migration test.
            patch.setenv(f"DXOS_{name.upper()}_URL", url.render_as_string(hide_password=False))
            patch.setenv(f"DXOS_{name.upper()}_SCHEMA", f"it_{name}_{suffix}")
        validate_distinct_targets()
        raw = create_engine(url)
        with raw.begin() as conn:
            conn.exec_driver_sql("CREATE TABLE public.unrelated_marker (note text PRIMARY KEY)")
            conn.exec_driver_sql("INSERT INTO public.unrelated_marker VALUES ('keep this record')")
            conn.exec_driver_sql(
                "CREATE TABLE public.alembic_version (version_num varchar(32) PRIMARY KEY)"
            )
            conn.exec_driver_sql(
                "INSERT INTO public.alembic_version VALUES ('legacy_flowbridge_001')"
            )
            conn.exec_driver_sql("CREATE SCHEMA core")
            conn.exec_driver_sql("CREATE TABLE core.legacy_marker (note text)")
            conn.exec_driver_sql("INSERT INTO core.legacy_marker VALUES ('old core is retained')")
            for name in DATABASES:
                quoted = conn.dialect.identifier_preparer.quote_identifier(schema_for(name))
                conn.exec_driver_sql(f"CREATE SCHEMA {quoted}")
            core_schema = conn.dialect.identifier_preparer.quote_identifier(schema_for("core"))
            conn.exec_driver_sql(f"CREATE TABLE {core_schema}.legacy_sidecar (note text)")
            conn.exec_driver_sql(
                f"INSERT INTO {core_schema}.legacy_sidecar VALUES ('unmanaged sidecar')"
            )
        for name in DATABASES:
            command.upgrade(alembic_config(name), "head")
            engines[name] = make_engine(name)
        from scripts.database.seed import seed_databases

        summary = seed_databases(DATABASES)
        assert sum(summary.values()) == 123
        yield {"engines": engines, "raw": raw, "dbname": dbname}
    finally:
        for engine in engines.values():
            engine.dispose()
        if raw is not None:
            raw.dispose()
        if created:
            assert dbname.startswith("dxos_it_schemas_")
            with admin.connect() as conn:
                quoted = conn.dialect.identifier_preparer.quote_identifier(dbname)
                conn.exec_driver_sql(f"DROP DATABASE {quoted} WITH (FORCE)")
        admin.dispose()
        patch.undo()


def assert_unrelated_data_preserved(raw):
    with raw.connect() as conn:
        assert conn.scalar(text("SELECT note FROM public.unrelated_marker")) == ("keep this record")
        assert conn.scalar(text("SELECT version_num FROM public.alembic_version")) == (
            "legacy_flowbridge_001"
        )
        assert conn.scalar(text("SELECT note FROM core.legacy_marker")) == ("old core is retained")
        quoted = conn.dialect.identifier_preparer.quote_identifier(schema_for("core"))
        assert conn.scalar(text(f"SELECT note FROM {quoted}.legacy_sidecar")) == (
            "unmanaged sidecar"
        )


def test_shared_database_has_four_isolated_heads_and_no_model_drift(shared_database):
    from scripts.database.seed import seed_databases
    from scripts.database.verify import verify_demo

    raw = shared_database["raw"]
    inspector = inspect(raw)
    for name in DATABASES:
        assert database_url(name).database == shared_database["dbname"]
        command.upgrade(alembic_config(name), "head")
        # Comparing any module must ignore other modules and legacy objects.
        command.check(alembic_config(name))
        expected = {table.name for table in metadata_for(name).tables.values()}
        if name == "core":
            expected.add("legacy_sidecar")
        assert set(inspector.get_table_names(schema=schema_for(name))) == expected | {
            "alembic_version"
        }
        with raw.connect() as conn:
            quoted = conn.dialect.identifier_preparer.quote_identifier(schema_for(name))
            assert conn.scalar(text(f"SELECT count(*) FROM {quoted}.alembic_version")) == 1
    assert seed_databases(DATABASES) == dict.fromkeys(DATABASES, 0)
    assert verify_demo()
    assert_unrelated_data_preserved(raw)


def test_schema_local_foreign_keys_and_tenant_boundary(shared_database):
    raw = shared_database["raw"]
    inspector = inspect(raw)
    for name in DATABASES:
        schema = schema_for(name)
        for target in metadata_for(name).tables.values():
            for fk in inspector.get_foreign_keys(target.name, schema=schema):
                assert fk["referred_schema"] == schema
    table = metadata_for("sales").tables["public.sales_orders"]
    engine = shared_database["engines"]["sales"]
    with engine.connect() as conn:
        row = dict(conn.execute(select(table)).mappings().first())
        row.update(id=uuid4(), org_id=uuid4(), order_number="CROSS-ORG-SCHEMA-TEST")
        with pytest.raises(IntegrityError) as error:
            conn.execute(table.insert().values(**row))
        assert error.value.orig.sqlstate == "23503"
        conn.rollback()


def test_schema_mode_detects_real_drift_on_owned_table(shared_database):
    raw = shared_database["raw"]
    with raw.begin() as conn:
        quoted = conn.dialect.identifier_preparer.quote_identifier(schema_for("sales"))
        conn.exec_driver_sql(f"ALTER TABLE {quoted}.sales_orders ADD accidental_column text")
    try:
        with pytest.raises(AutogenerateDiffsDetected):
            command.check(alembic_config("sales"))
    finally:
        with raw.begin() as conn:
            quoted = conn.dialect.identifier_preparer.quote_identifier(schema_for("sales"))
            conn.exec_driver_sql(f"ALTER TABLE {quoted}.sales_orders DROP accidental_column")
    command.check(alembic_config("sales"))
    assert_unrelated_data_preserved(raw)


def test_core_seed_stays_unconnected_and_has_no_tenant_table(shared_database):
    sources = metadata_for("core").tables["public.data_sources"]
    with shared_database["engines"]["core"].connect() as connection:
        rows = connection.execute(select(sources)).mappings().all()
    assert len(rows) == 3
    assert all(row["status"] == "DRAFT" for row in rows)
    assert all(row["database_name"] == shared_database["dbname"] for row in rows)
    assert "public.organizations" not in metadata_for("core").tables


def test_schema_forward_only_guards_and_offline_ddl_preserve_neighbors(
    shared_database,
):
    import json

    from scripts.database.registry import REPOSITORY_ROOT
    from scripts.database.seed import seed_databases
    from scripts.database.verify import verify_demo

    legacy_priorities = json.loads(
        (REPOSITORY_ROOT / "tests/fixtures/database/handoff-fingerprints.json").read_text()
    )["legacy_core_priorities"]

    raw = shared_database["raw"]
    # No target comes from a developer's .env: the fixture created this database.
    assert database_url("core").database.startswith("dxos_it_schemas_")
    for name in DATABASES:
        config = alembic_config(name)
        config.attributes["allow_core_data_reset"] = name == "core"
        if name == "core":
            command.downgrade(config, "base")
        else:
            from tests.e2e.database.disposable_reset import reset_owned_disposable

            with pytest.raises(RuntimeError, match="Review"):
                command.downgrade(config, "base")
            reset_owned_disposable(raw, name)
        expected = {"alembic_version"}
        if name == "core":
            expected.add("legacy_sidecar")
        assert set(inspect(raw).get_table_names(schema=schema_for(name))) == expected
    assert_unrelated_data_preserved(raw)
    for revision, priorities in (
        ("core_0001", {"P0"}),
        ("core_0002", {"P0", "P1"}),
        ("core_0003", {"P0", "P1", "P2"}),
    ):
        command.upgrade(alembic_config("core"), revision)
        expected = {name for name, priority in legacy_priorities.items() if priority in priorities}
        assert set(inspect(raw).get_table_names(schema=schema_for("core"))) == expected | {
            "alembic_version",
            "legacy_sidecar",
        }
    for name in ("sales", "warehouse", "logistics"):
        output = StringIO()
        config = alembic_config(name)
        config.output_buffer = output
        command.upgrade(config, "head", sql=True)
        sql = output.getvalue()
        assert "CREATE TABLE public." not in sql
        with raw.connect().execution_options(isolation_level="AUTOCOMMIT") as conn:
            quoted = conn.dialect.identifier_preparer.quote_identifier(schema_for(name))
            conn.exec_driver_sql(f"DROP TABLE {quoted}.alembic_version")
            conn.exec_driver_sql("SET search_path TO pg_catalog")
            conn.exec_driver_sql(sql, execution_options={"no_parameters": True})
    for name in DATABASES:
        command.upgrade(alembic_config(name), "head")
        command.check(alembic_config(name))
    assert sum(seed_databases(DATABASES).values()) == 123
    assert verify_demo()
    assert_unrelated_data_preserved(raw)


def test_generated_revision_stays_portable_and_executes_in_target_schema(
    shared_database,
):
    import sqlalchemy as sa
    from alembic.autogenerate import produce_migrations, render_python_code
    from alembic.migration import MigrationContext
    from alembic.operations import Operations, ops
    from scripts.database.migration import comparison_metadata, portable_revisions

    schema = schema_for("sales")
    metadata = comparison_metadata("sales", schema)
    customers = metadata.tables[f"{schema}.customers"]
    customers.append_column(sa.Column("portable_probe", sa.String(50), nullable=True))
    probe = sa.Table(
        "portable_revision_probe",
        metadata,
        sa.Column("id", sa.Uuid, primary_key=True),
        sa.Column("org_id", sa.Uuid, nullable=False),
        sa.Column("customer_id", sa.Uuid, nullable=False),
        sa.ForeignKeyConstraint(
            ["org_id", "customer_id"],
            [f"{schema}.customers.org_id", f"{schema}.customers.id"],
            name="fk_portable_probe_customer",
        ),
        schema=schema,
    )
    sa.Index("ix_portable_probe_customer", probe.c.customer_id)
    owned = {table.name for table in metadata.tables.values()}

    def include_name(name, type_, parent_names):
        if type_ == "schema":
            return name == schema
        if type_ == "table":
            return parent_names.get("schema_name") == schema and name in owned
        return True

    def invoke(operations, operation):
        if isinstance(operation, ops.OpContainer):
            for child in operation.ops:
                invoke(operations, child)
        else:
            operations.invoke(operation)

    raw = shared_database["raw"]
    with raw.begin() as conn:
        context = MigrationContext.configure(
            conn,
            opts={
                "dxos_schema": schema,
                "target_metadata": metadata,
                "include_schemas": True,
                "include_name": include_name,
                "compare_type": True,
            },
        )
        directives = [produce_migrations(context, metadata)]
        portable_revisions(context, (), directives)
        script = directives[0]
        upgrade = render_python_code(script.upgrade_ops, migration_context=context)
        downgrade = render_python_code(script.downgrade_ops, migration_context=context)
        assert "schema='public'" in upgrade
        assert "public.customers.org_id" in upgrade
        assert schema not in upgrade
        assert schema not in downgrade
        operations = Operations(context)
        invoke(operations, script.upgrade_ops)
        inspector = inspect(conn)
        assert "portable_probe" in {
            column["name"] for column in inspector.get_columns("customers", schema=schema)
        }
        foreign_keys = inspector.get_foreign_keys(probe.name, schema=schema)
        assert foreign_keys[0]["referred_schema"] == schema
        invoke(operations, script.downgrade_ops)
        inspector = inspect(conn)
        assert probe.name not in inspector.get_table_names(schema=schema)
        assert "portable_probe" not in {
            column["name"] for column in inspector.get_columns("customers", schema=schema)
        }
    command.check(alembic_config("sales"))
    assert_unrelated_data_preserved(raw)
